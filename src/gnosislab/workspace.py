"""gnosislab init — scaffold a fully isolated workspace from a folder.

One command produces everything a sandbox needs:

    <dir>/.daemon/daemon.toml   isolated config: loopback console port,
                                HOME redirect, own ML_* port sub-block
    <dir>/.daemon/drivers/      session-driver copies (the sandbox owns
                                them — edits never touch the package)
    <dir>/home/                 sandbox HOME — ~/.ml-* state, opencode's
                                session DB, every service database
    <dir>/work/                 default loop workdir
    <dir>/env                   sourceable: HOME + ML_*_PORT exports so
                                `gnosislab start all` / `opencode` TUI in
                                this shell resolve the sandbox stack
    <dir>/task.md, verify.py    runnable starter task + verdict checker

Port allocation: service sub-blocks are 50-port spans at 28N00
(280xx is the system defaults). Consoles live in 283xx. Allocated
blocks are registered in ~/.config/gnosislab/workspaces.json so two
workspaces never collide even while their services are down; live
listeners are probed too, so hand-built sandboxes are also avoided.
"""

from __future__ import annotations

import json
import os
import shutil
import socket
import sys
from pathlib import Path

REGISTRY = Path.home() / ".config" / "gnosislab" / "workspaces.json"

# 50-port spans at 28N00 — one per workspace. 280xx is the system
# default sub-block (never handed out); start at 28100.
_BLOCK_BASES = range(28100, 29000, 100)
_CONSOLE_BASES = range(28300, 28400)   # shared 283xx console block

_SERVICES = ("agora", "arete", "zetesis", "episteme", "anamnesis")

DAEMON_TOML = """\
# {name} — isolated gnosislab workspace (generated by `gnosislab init`).
#
# [daemon.env] is applied to the daemon's os.environ at serve(), so
# every child (driver -> agent -> checker) inherits the sandbox: HOME
# redirect lands opencode's session DB and ~/.ml-* service state under
# home/, and the ML_* ports point the service stack at this
# workspace's sub-block — other stacks are unreachable, not just
# unused. Free model opencode/big-pickle needs no auth.

[daemon]
listen = "127.0.0.1"
port = {console_port}
max_concurrent = 1

[daemon.env]
HOME = "{home}"
OPENCODE_BIN = "{opencode_bin}"
OPENCODE_MODEL = "opencode/big-pickle"
OPENCODE_RUN_ARGS = "--auto --standalone"
{env_ports}

# --- agent profiles -----------------------------------------------------
# session mode: one persistent driver per loop; send/status/cancel/
# fork over stdio JSONL; turn_end is the boundary, never the verdict.
# {{config_dir}} = this file's directory (.daemon) -> drivers live in
# .daemon/drivers/ so the workspace carries its own copies.

[agents.opencode_service]
mode = "session"
driver = ["python3", "{{config_dir}}/drivers/opencode_service.py",
          "--workdir", "{{workdir}}", "--session", "{{session_id}}"]

# protocol smoke test — no real model; FAKE_DRIVER_* env knobs script
# ready/turn_end/cancel/fork behaviour.
[agents.fake_session]
mode = "session"
driver = ["python3", "{{config_dir}}/drivers/fake_session_driver.py"]

# exec-mode profile — one opencode process per turn (pre-session
# architecture, still fully supported). --standalone: private server
# per invocation; --auto: auto-approve permissions (stdin is
# /dev/null — a prompt would die on EOF).
[agents.opencode]
start = ["{opencode_bin}", "run", "--standalone", "--auto",
         "--format", "json", "-m", "opencode/big-pickle", "{{prompt}}"]
resume = ["{opencode_bin}", "run", "--standalone", "--auto",
          "--format", "json", "-m", "opencode/big-pickle",
          "--session", "{{session_id}}", "{{prompt}}"]
session_id_regex = '"sessionID"\\s*:\\s*"([^"]+)"'

[daemon.limits]
max_turns = 8              # attempts per episode -> BLOCKED
stagnation = 3             # identical checker outputs -> fork -> BLOCKED
check_timeout = 300        # checker ceiling -> CHECK_ERROR
feedback_bytes = 8192
output_bytes = 65536
driver_ready_seconds = 60  # opencode service cold start is slow
driver_status_seconds = 15 # responsiveness probe — never a turn clock
shutdown_grace = 5
"""

ENV_FILE = """\
# Source to put this shell inside the workspace:
#   source {env_path}
# Then `gnosislab start all`, `gnosislab daemon …`, and `opencode`
# all resolve the sandbox stack (sandbox HOME, sandbox ports).
export GNOSISLAB_WORKSPACE="{root}"
export HOME="{home}"
{exports}
"""

TASK_MD = """\
Write hello.py in this directory that prints "hello from gnosislab",
then run it and save its exact stdout to hello_out.txt in the same
directory.
"""

VERIFY_PY = '''\
#!/usr/bin/env python3
"""Loop checker — emits a GNOSISLAB_VERDICT structured diagnostic as
its last stdout line. Exit code is the ONLY verdict: 0 verified,
1 continue, >=2 broken checker. Runs with cwd=workdir (the daemon
spawns checkers there).
"""
import json
import subprocess
import sys
from pathlib import Path

wd = Path.cwd()
failures = []

src = wd / "hello.py"
out = wd / "hello_out.txt"

if not src.is_file():
    failures.append({"name": "source_exists", "expected": "hello.py",
                     "got": "missing",
                     "hint": "create hello.py in the workdir"})
elif not out.is_file():
    failures.append({"name": "output_exists",
                     "expected": "hello_out.txt", "got": "missing",
                     "hint": "run the script and save its stdout"})
else:
    try:
        expected = subprocess.run(
            [sys.executable, str(src)], capture_output=True,
            text=True, timeout=30)
        if expected.returncode != 0:
            failures.append({"name": "script_runs",
                             "expected": "exit 0",
                             "got": f"exit {expected.returncode}: "
                                    f"{expected.stderr[-300:]}",
                             "hint": "fix the script error"})
        elif expected.stdout != out.read_text():
            failures.append({"name": "output_matches",
                             "expected": expected.stdout[:200],
                             "got": out.read_text()[:200],
                             "hint": "hello_out.txt must equal the "
                                     "script's exact stdout"})
    except subprocess.TimeoutExpired:
        failures.append({"name": "script_runs", "expected": "<30s",
                         "got": "timeout",
                         "hint": "script must terminate quickly"})

print("GNOSISLAB_VERDICT " + json.dumps(
    {"schema": 1, "pass": not failures, "failures": failures}))
sys.exit(0 if not failures else 1)
'''

README_MD = """\
# {name} — gnosislab workspace

Isolated experiment sandbox. Everything this stack writes — service
databases, opencode sessions, daemon state — lands inside this
folder. Delete the folder and the whole stack is gone.

## Layout

| path | what lives there |
|---|---|
| `home/` | sandbox HOME — `~/.ml-*` service state, opencode session DB |
| `work/` | default loop workdir (the agent's cwd) |
| `.daemon/` | daemon state root — `daemon.toml`, loops/, console token |
| `.daemon/drivers/` | session drivers this workspace owns |
| `env` | `source env` → this shell runs inside the sandbox |
| `task.md` / `verify.py` | starter task + verdict checker |

## Run it

```bash
source {env_path}                 # shell now inside the sandbox
gnosislab start all               # service stack -> home/.ml-*
gnosislab daemon serve --state-dir .daemon   # terminal 1

gnosislab daemon start --agent opencode_service \\
    --task task.md --workdir work \\
    --state-dir .daemon --check {root}/verify.py    # terminal 2

tail -f .daemon/loops/loop-001/events.jsonl   # live opencode events
opencode                                      # TUI on the same session DB
```

Console: http://127.0.0.1:{console_port}/ — token in
`.daemon/management-token`.

## Ports

| allocation | ports |
|---|---|
| daemon console | {console_port} |
| service sub-block | {block}–{block_end} |

Tear down: `gnosislab stop all && gnosislab daemon shutdown
--state-dir .daemon`, or Ctrl-C the serves. Nothing outside this
folder is touched.
"""


def _used_ports() -> set[int]:
    """Ports promised to registered workspaces plus the defaults."""
    used: set[int] = set()
    try:
        reg = json.loads(REGISTRY.read_text())
        for entry in reg.values():
            used.update(int(p) for p in entry.get("ports", []))
    except (OSError, ValueError):
        pass
    # system default sub-block is never allocatable
    used.update(range(28050, 28092))
    return used


def _listening(port: int) -> bool:
    """True if something answers a loopback connect on this port."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(0.2)
        return s.connect_ex(("127.0.0.1", port)) == 0


def _service_ports(base: int) -> list[int]:
    """The 10 ports a block owns: 5 services x (mcp, gui)."""
    return [base + i * 10 + j for i in range(5) for j in (0, 1)]


def _allocate() -> tuple[int, int, list[int]]:
    """(console_port, block_base, owned_ports) — first free slots."""
    used = _used_ports()
    block = None
    for base in _BLOCK_BASES:
        ports = _service_ports(base)
        if (not any(p in used for p in ports)
                and not any(_listening(p) for p in ports)):
            block = base
            break
    if block is None:
        raise RuntimeError("no free 28N00 service sub-block — "
                           "tear down a workspace or widen "
                           "_BLOCK_BASES")
    console = None
    for port in _CONSOLE_BASES:
        if port not in used and not _listening(port):
            console = port
            break
    if console is None:
        raise RuntimeError("no free console port in 283xx")
    return console, block, _service_ports(block) + [console]


def _register(root: Path, ports: list[int]) -> None:
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    try:
        reg = json.loads(REGISTRY.read_text())
    except (OSError, ValueError):
        reg = {}
    reg[str(root)] = {"ports": ports}
    REGISTRY.write_text(json.dumps(reg, indent=2) + "\n")


def _unregister(root: Path) -> None:
    try:
        reg = json.loads(REGISTRY.read_text())
        if reg.pop(str(root), None) is not None:
            REGISTRY.write_text(json.dumps(reg, indent=2) + "\n")
    except (OSError, ValueError):
        pass


def _drivers_dir() -> Path:
    from gnosislab_daemon import drivers
    return Path(drivers.__file__).parent


def init_workspace(target: str, *, force: bool = False) -> int:
    root = Path(target).expanduser().resolve()
    if root.is_dir() and any(root.iterdir()) and not force:
        print(f"gnosislab init: {root} is not empty "
              "(use --force to scaffold anyway)", file=sys.stderr)
        return 2

    opencode = (shutil.which("opencode")
                or "/home/x/.opencode/bin/opencode")
    try:
        console, block, ports = _allocate()
    except RuntimeError as exc:
        print(f"gnosislab init: {exc}", file=sys.stderr)
        return 1

    try:
        home = root / "home"
        daemon_dir = root / ".daemon"
        drivers_dir = daemon_dir / "drivers"
        workdir = root / "work"
        for d in (home, drivers_dir, workdir):
            d.mkdir(parents=True, exist_ok=True)

        for src in _drivers_dir().glob("*.py"):
            if src.name != "__init__.py":
                shutil.copy2(src, drivers_dir / src.name)

        env_ports = "\n".join(
            f'ML_{n.upper()}_PORT = "{block + i * 10}"\n'
            f'ML_{n.upper()}_GUI_PORT = "{block + i * 10 + 1}"'
            for i, n in enumerate(_SERVICES))
        (daemon_dir / "daemon.toml").write_text(DAEMON_TOML.format(
            name=root.name, console_port=console, home=home,
            opencode_bin=opencode, env_ports=env_ports))

        exports = "\n".join(
            f"export ML_{n.upper()}_PORT={block + i * 10}\n"
            f"export ML_{n.upper()}_GUI_PORT={block + i * 10 + 1}"
            for i, n in enumerate(_SERVICES))
        (root / "env").write_text(ENV_FILE.format(
            env_path=root / "env", root=root, home=home,
            exports=exports))

        (root / "task.md").write_text(TASK_MD)
        verify = root / "verify.py"
        verify.write_text(VERIFY_PY)
        verify.chmod(0o755)

        (root / "README.md").write_text(README_MD.format(
            name=root.name, env_path=root / "env", root=root,
            console_port=console, block=block, block_end=block + 49))

        _register(root, ports)
    except Exception:
        _unregister(root)
        raise

    print(f"workspace: {root}")
    print(f"  console  :{console}   services {block}-{block + 49}"
          f"   (registered in {REGISTRY})")
    print(f"\n  source {root / 'env'}")
    print(f"  gnosislab start all")
    print(f"  gnosislab daemon serve --state-dir {daemon_dir}")
    return 0
