def test_cli_dispatch_all_formats(stores, tmp_path):
    epi, ana = stores
    for fmt, doc_name in (
        ("ro-crate", "ro-crate-metadata.json"),
        ("prov", "prov.json"),
        ("jsonld", "export.jsonld"),
    ):
        out = tmp_path / fmt
        rc = export_cli(
            [
                "--programme", "prog-t1",
                "--format", fmt,
                "--out", str(out),
                "--episteme-db", str(epi),
                "--anamnesis-db", str(ana),
            ]
        )
        assert rc == 0, fmt
        assert (out / doc_name).exists()
        assert (out / "payload/MANIFEST.json").exists()
