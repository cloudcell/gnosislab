def test_prov_structure(stores, tmp_path):
    epi, ana = stores
    snap = load_snapshot(epi, ana, programme_id="prog-t1")
    out = export_prov(snap, tmp_path / "prov")

    doc = json.loads((out / "prov.json").read_text())
    assert doc["prefix"]["prov"] == "http://www.w3.org/ns/prov#"

    # agent + trial activity with recorded start/end
    agent = doc["agent"]["gl:agent/gnosislab"]
    assert agent["prov:type"]["$"] == "prov:SoftwareAgent"
    trial = doc["activity"]["gl:trial/trl-t1"]
    assert trial["prov:type"]["$"] == "gl:Trial"
    assert trial["prov:startTime"]["$"] == "2026-10-01T00:03:00Z"
    assert trial["prov:endTime"]["$"] == "2026-10-01T00:03:12Z"

    # entities carry their roles
    assert doc["entity"]["gl:hypothesis/hyp-t1"]["prov:type"][1]["$"] == (
        "prov:Plan"
    )
    assert doc["entity"]["gl:claim/clm-t1"]["gl:confidence"] == 0.9
    assert doc["entity"]["gl:verdict/cnc-t1"]["prov:type"]["$"] == (
        "gl:Verdict"
    )

    def relvals(key, prop):
        return [v[prop] for v in doc[key].values() if prop in v]

    # observation + artifact generated by the trial; verdict by conclusion
    gen = relvals("wasGeneratedBy", "prov:entity")
    assert "gl:observation/obs-t1" in gen
    assert "gl:artifact/ffff" in gen
    assert "gl:verdict/cnc-t1" in gen

    # trial used hypothesis + code; conclusion used the evidence entity
    used = relvals("used", "prov:entity")
    assert "gl:hypothesis/hyp-t1" in used
    assert "gl:code/aabbcc" in used
    assert "gl:trial/trl-t1" in used

    # claim edge → wasDerivedFrom claim → trial
    drv = list(doc["wasDerivedFrom"].values())
    assert {
        "prov:generatedEntity": "gl:claim/clm-t1",
        "prov:usedEntity": "gl:trial/trl-t1",
        "prov:hadRole": {"$": "gl:derived_from", "type": "prov:QUALIFIED_NAME"},
    } in drv

    # agent associated with both activities
    assoc = relvals("wasAssociatedWith", "prov:activity")
    assert "gl:trial/trl-t1" in assoc
    assert "gl:conclusion/cnc-t1" in assoc

    # programme collects its hypothesis
    members = doc["hadMember"]["gl:members/prog-t1"]["prov:entity"]
    assert members == "gl:hypothesis/hyp-t1"

    # payload + manifest still emitted
    assert (out / "payload/MANIFEST.json").exists()
    assert (out / "payload/results/trl-t1.json").exists()


def test_prov_external_ref_visible(stores, tmp_path):
    epi, ana = stores
    conn = sqlite3.connect(ana)
    conn.execute(
        "INSERT INTO claim_edges VALUES "
        "('edg-x','clm-t1','ext-9','evidence','supports','src',"
        "'2026-10-01T00:05:02Z')"
    )
    conn.commit()
    conn.close()
    snap = load_snapshot(epi, ana, programme_id="prog-t1")
    doc = json.loads(
        (export_prov(snap, tmp_path / "prov") / "prov.json").read_text()
    )
    ext = doc["entity"]["gl:external/ext-9"]
    assert ext["prov:type"]["$"] == "gl:ExternalRef"
    # 'supports' is influence, not derivation
    inf = list(doc["wasInfluencedBy"].values())
    assert inf[0]["prov:influencer"] == "gl:external/ext-9"


